import streamlit as st
import pandas as pd
import os
import plotly.express as px

st.set_page_config(
    page_title="AI Personal Expense Analyzer",
    page_icon="💰",
    layout="wide"
)

FILE = "expenses.csv"

st.title("AI Personal Expense Analyzer")
st.write("Track expenses, manage your budget and understand your spending.")

if "expenses" not in st.session_state:
    if os.path.exists(FILE):
        st.session_state.expenses = pd.read_csv(FILE).to_dict("records")
    else:
        st.session_state.expenses = []

if "budget" not in st.session_state:
    st.session_state.budget = 5000

st.sidebar.header("Monthly Budget")
st.session_state.budget = st.sidebar.number_input(
    "Enter your budget (Rs.)",
    min_value=0,
    value=int(st.session_state.budget),
    step=500
)

st.subheader("Add a New Expense")

with st.form("expense_form"):
    category = st.selectbox(
        "Expense category",
        ["Food", "Travel", "Shopping", "Education", "Bills", "Health", "Other"]
    )
    amount = st.number_input(
        "Expense amount (Rs.)",
        min_value=1,
        value=100,
        step=50
    )
    note = st.text_input("Description (optional)")
    submitted = st.form_submit_button("Add Expense")

    if submitted:
        st.session_state.expenses.append({
            "Category": category,
            "Amount": amount,
            "Description": note
        })
        pd.DataFrame(st.session_state.expenses).to_csv(FILE, index=False)
        st.success("Expense saved successfully!")
        st.rerun()

df = pd.DataFrame(
    st.session_state.expenses,
    columns=["Category", "Amount", "Description"]
)

total = int(df["Amount"].sum()) if not df.empty else 0
remaining = st.session_state.budget - total

st.subheader("Your Expense Dashboard")

col1, col2, col3 = st.columns(3)
col1.metric("Monthly Budget", f"Rs. {st.session_state.budget}")
col2.metric("Total Spent", f"Rs. {total}")
col3.metric("Remaining Budget", f"Rs. {remaining}")

if remaining < 0:
    st.error(f"You exceeded your budget by Rs. {abs(remaining)}.")
elif st.session_state.budget > 0 and remaining == 0:
    st.warning("Your entire budget has been used.")
else:
    st.success("You are within your budget.")

if not df.empty:
    st.subheader("Category-wise Spending")
    chart_data = df.groupby("Category")["Amount"].sum()
    st.bar_chart(chart_data)
    st.subheader("Expense Pie Chart")
    fig = px.pie(
        chart_data.reset_index(),
        names="Category",
        values="Amount",
        title="Category-wise Expense",
        hole=0.4
    )
    st.plotly_chart(fig, use_container_width=True)

    st.subheader("Expense History")
    st.dataframe(df, use_container_width=True)

    st.subheader("Spending Insights")
    average = total / len(df)
    st.write(f"You have recorded {len(df)} expenses.")
    st.write(f"Your average expense is Rs. {average:.2f}.")

    highest = df.groupby("Category")["Amount"].sum().idxmax()
    st.write(f"Your highest-spending category is: {highest}.")

    if total > st.session_state.budget * 0.8:
        st.warning("You have used over 80% of your budget. Try reducing optional spending.")
    else:
        st.info("Keep tracking your spending to understand your habits.")

    if st.button("Delete All Expenses"):
        st.session_state.expenses = []
        if os.path.exists(FILE):
            os.remove(FILE)
        st.rerun()
else:
    st.info("No expenses added yet. Add your first expense above.")

st.caption("Project demo: spending insights are rule-based, not generated by a trained AI model.")
